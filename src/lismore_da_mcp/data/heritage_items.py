"""LEP 2012 Schedule 5 Parts 1 and 3 — the heritage items and archaeological sites.

ROADMAP.md C2. Transcribed row for row from `documents/lep/lep-2012-nsw-full.txt`
(Schedule 5, 2026-09-27): 113 items (I1–I113) and 18 archaeological sites
(A1–A18), in the LEP's own order, every field as the LEP prints it — including
its slips, such as I49's address "188 Keen" with no street type. Part 2, the
seven conservation areas, is carried in `data/heritage.py` beside their DCP
Chapter 12 precinct policies. `scripts/audit_heritage.py` re-reads the schedule
from the LEP text and diffs every row both ways.

**Why carry a table the state heritage layer already maps.** The layer behind
`lookup_site_constraints` answers "is the point under this address mapped as
heritage" — when it can be reached, which from the environment this was written
in it could not (the proxy refused the connection). The schedule answers three
things the layer cannot:

- **Offline, and from the instrument.** Schedule 5 *is* the list cl 5.10 refers
  to; the layer is a state dataset drawn from it. An address that appears here
  is listed whether or not a map service is up.
- **The street, for the vicinity rule.** cl 5.10(5)(c) reaches land "within the
  vicinity of" a heritage item, and the layer, being a point query, has no idea
  what is next door. A listed item on the same street is the evidence an
  applicant can act on. It is positive-only: an item round the corner or across
  a lane is just as near, so no match here clears anything.
- **What the listing covers.** The item name says whether it is a building, its
  grounds, street trees, or an interior (A5, "House interior, 'Locheil'") — the
  last matters because cl 5.10(2)(b) reaches inside a heritage item only for
  what Schedule 5 specifies.

**"State" in the Significance column is not the State Heritage Register.** The
column records the significance the listing assessed; SHR listing is a separate
regime under the Heritage Act 1977, and `data/referrals.py` handles it. Nothing
here should be read as putting an item on the SHR.

Each row is (item_no, suburb, item_name, address, property_description,
significance). An empty property description is the LEP's, not a gap.
"""

